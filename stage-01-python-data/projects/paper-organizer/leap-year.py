def 是否闰年(年份):
    """
    判断一个年份是否是闰年。
    闰年规则：
      1. 能被 4 整除，但不能被 100 整除；
      2. 或者能被 400 整除。
    """
    if (年份 % 4 == 0 and 年份 % 100 != 0) or 年份 % 400 == 0:
        return True      # 满足条件：是闰年
    else:
        return False     # 不满足：不是闰年


# 测试用例
print(2000, 是否闰年(2000))   # True   (能被400整除)
print(1900, 是否闰年(1900))   # False  (能被100整除但不能被400整除)
print(2024, 是否闰年(2024))   # True   (能被4整除且不能被100整除)
print(2023, 是否闰年(2023))   # False  (不能被4整除)
