def 秒转时分秒(总秒数):
    """把总秒数转换成"时:分:秒"的字符串格式。"""
    时 = 总秒数 // 3600          # 1小时=3600秒，求能分成几个完整小时
    分 = 总秒数 // 60 % 60       # 先求总分钟数，再去掉完整小时后剩下的分钟
    秒 = 总秒数 % 60             # 去掉完整分钟后剩下的秒数
    return f"{时}:{分}:{秒}"     # 用 f-string 把变量塞进字符串


# 测试用例
print(3661, 秒转时分秒(3661))   # "1:1:1"
print(59, 秒转时分秒(59))       # "0:0:59"
print(125, 秒转时分秒(125))     # "0:2:5"
