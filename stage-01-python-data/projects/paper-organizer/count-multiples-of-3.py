"""
作业二：统计 1~50 里能被 3 整除的数字
2026-08-26 编写（巩固 for / range / % / 计数器）
"""

# ===== 思路 =====
# 1. 用一个"计数器"变量统计个数，从 0 开始
# 2. for 循环从 1 数到 50，挨个检查
# 3. 能被 3 整除（i % 3 == 0）就打印，并让计数器 +1
# 4. 循环结束后报告总数

计数 = 0                        # 计数器：统计一共有多少个（起点 0）

for i in range(1, 51):          # 从 1 数到 50（注意：右边写 51 才包含 50）
    if i % 3 == 0:              # 能被 3 整除（余数为 0）
        print(i)                # 打印这个数
        计数 += 1               # 找到一个，计数器 +1（等价于 计数 = 计数 + 1）

print("一共", 计数, "个")       # 循环结束，打印总数
