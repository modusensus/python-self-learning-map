"""
作业一：体重转换器（斤 → 千克）
2026-08-26 编写（巩固 def 函数 / 参数 / return）

1 斤 = 0.5 千克
"""

def 斤转千克(斤):
    """把"斤"转换成"千克"：千克 = 斤 × 0.5"""
    千克 = 斤 * 0.5    # 1 斤 = 0.5 千克，乘以 0.5 换算
    return 千克        # 把结果交出去（return = 返回值）

# 调用函数转换 3 个不同的值，并打印出来
print(12, "斤 =", 斤转千克(12), "千克")        # 12 斤 → 6.0 千克
print(12.5, "斤 =", 斤转千克(12.5), "千克")    # 12.5 斤 → 6.25 千克（浮点数也能算）
print(100, "斤 =", 斤转千克(100), "千克")      # 100 斤 → 50.0 千克
