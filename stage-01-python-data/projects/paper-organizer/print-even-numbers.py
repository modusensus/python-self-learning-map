"""
练习：打印 1 到 10 的所有偶数
2026-08-18 编写（复习 for / range / % 的实战）
"""

# ============================================================
# 方案 B：让 range 数到 0，再用条件把 0 "过滤"掉
# ============================================================
# range(11) 生成 0,1,2,...,10（从 0 开始，共 11 个数字）
for i in range(11):
    # 条件："i 不等于 0" 并且 "i 是偶数"
    #   i != 0       → 排除 0（!= 是"不等于"）
    #   i % 2 == 0   → 能被 2 整除，即偶数（% 是"取余数"）
    #   and          → "并且"，两边都要成立才算真
    if i != 0 and i % 2 == 0:
        print(i, "是偶数")    # 满足条件才打印


# ============================================================
# 方案 A（推荐，更干净）：用 range(1, 11) 从源头避开 0
# ============================================================
# range(1, 11) 从 1 数到 10（包含 1，不包含 11），共 10 个数字
for i in range(1, 11):
    if i % 2 == 0:            # 只要判断"是偶数"就够了，不会有 0
        print(i, "是偶数")


# ============================================================
# 两种方案辨析
# ============================================================
# 方案 A：range(1, 11)            → "源头"上就不让它数到 0，代码最简洁 ✅
# 方案 B：range(11) + i != 0 and  → 放数据进来，再用条件"过滤"掉不要的
#
# 什么时候用哪个？
#   - 能改起始数字 → 用方案 A（省事、好懂）
#   - 数字来自别处改不了源头 → 用方案 B（"过滤"思维，数据分析里很常用）
