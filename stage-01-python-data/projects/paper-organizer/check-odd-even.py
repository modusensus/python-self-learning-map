# ===== 思路 =====
# 1. 定义一个函数，接收一个参数"数"
# 2. 用 % 取余判断：数 % 2 == 0 → 能被 2 整除 → 偶数
# 3. 否则 → 奇数
# 4. 用 return 返回"偶数"或"奇数"字符串

def 判断奇偶(数):
    """判断一个数是奇数还是偶数"""
    if 数 % 2 == 0:        # 如果能被 2 整除，余数为 0
        return "偶数"
    else:                   # 否则就是奇数
        return "奇数"

# 调用函数判断 3 个数
print(10, "是", 判断奇偶(10))   # 10 是 偶数
print(7, "是", 判断奇偶(7))     # 7 是 奇数
print(88, "是", 判断奇偶(88))   # 88 是 偶数
