def 摄氏转华氏(摄氏):
    """摄氏温度 → 华氏温度，公式：华氏 = 摄氏 × 9/5 + 32"""
    华氏 = 摄氏 * 9 / 5 + 32
    return 华氏


def 华氏转摄氏(华氏):
    """华氏温度 → 摄氏温度，公式：摄氏 = (华氏 - 32) × 5/9"""
    摄氏 = (华氏 - 32) * 5 / 9
    return 摄氏


# 测试用例
print(0, 摄氏转华氏(0))         # 32.0
print(100, 摄氏转华氏(100))     # 212.0
print(32, 华氏转摄氏(32))       # 0.0
print(212, 华氏转摄氏(212))     # 100.0
