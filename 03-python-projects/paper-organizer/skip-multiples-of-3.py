"""
练习：打印 1~20 中"不是 3 的倍数"的数字
2026-08-18 编写（巩固 continue / % / range 的实战）
"""

# ===== 方案A：用 continue 跳过 3 的倍数 =====
for i in range(1, 21):       # 从 1 数到 20（包含 1，不包含 21）
    if i % 3 == 0:           # 如果 i 是 3 的倍数（能被 3 整除）
        continue             # 跳过本次，不打印
    print(i)                 # 不是 3 的倍数才打印

# ===== 方案B：用 != 直接判断"不是 3 的倍数" =====
for i in range(1, 21):       # 从 1 数到 20
    if i % 3 != 0:           # i 不是 3 的倍数
        print(i)             # 直接打印