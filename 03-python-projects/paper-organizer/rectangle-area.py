# ===== 思路 =====
# 1. 定义一个函数，接收两个参数：长 和 宽
# 2. 函数内部计算：面积 = 长 × 宽
# 3. 用 return 把面积返回出来
# 4. 调用函数，打印结果

def 矩形面积(长, 宽):
    """计算矩形的面积：面积 = 长 × 宽"""
    面积 = 长 * 宽    # 矩形面积公式
    return 面积        # 把计算结果交出去

# 调用函数计算两个不同矩形的面积
print(5, "*", 3, "=", 矩形面积(5, 3))        # 5 × 3 = 15
print(7, "*", 2.5, "=", 矩形面积(7, 2.5))    # 7 × 2.5 = 17.5
