"""
作业四：累加器（循环 + 计数器）
2026-08-19 编写（巩固 for 循环 / 累加器思路）

计算 1 + 2 + 3 + ... + 100 的总和
"""

# ===== 思路 =====
# 1. 用一个变量"总和"当累加器，起点为 0
# 2. for 循环从 1 到 100，每轮把 i 加进"总和"
# 3. 循环结束后，"总和"就是 1~100 的累加结果

总和 = 0                        # 累加器：从 0 开始

for i in range(1, 101):         # 从 1 到 100（右边写 101 才包含 100）
    总和 += i                   # 把当前的 i 加到总和中（等价于 总和 = 总和 + i）

print("1 加到 100 的总和是", 总和)  # 结果：5050

# 拓展：高斯公式可以直接算 → 100 × 101 ÷ 2 = 5050
# 但这里用循环是为了练习"累加器"这个编程思维
